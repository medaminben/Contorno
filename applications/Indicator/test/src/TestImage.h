/// The same JPEG with an APP1 "Exif" segment holding the Orientation tag
/// (0x0112, SHORT) `orientation` right after SOI. Stored 40 x 20; shown
/// 20 x 40 for 5-8.
inline std::string jpeg_with_orientation(unsigned char orientation) {
    // little-endian TIFF header, one IFD0 entry: Orientation (0x0112), SHORT, 1, value
    unsigned char const app1[] = {0xFF, 0xE1, 0x00, 0x22, 'E', 'x', 'i', 'f', 0, 0, 'I', 'I', 0x2A, 0x00,
                                  0x08, 0x00, 0x00, 0x00, 0x01, 0x00, 0x12, 0x01, 0x03, 0x00, 0x01, 0x00,
                                  0x00, 0x00, orientation, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
    std::string jpeg = plain_jpeg_bytes();
    jpeg.insert(2, reinterpret_cast<char const*>(app1), sizeof app1);
    return jpeg;
}

/// Writes `bytes` to `path`. False when it cannot be written.
inline bool write_bytes(std::filesystem::path const& path, std::string const& bytes) {
    std::ofstream file(path, std::ios::binary);
    file.write(bytes.data(), static_cast<std::streamsize>(bytes.size()));
    file.close();
    return static_cast<bool>(file);
}

/// A 40 x 20 JPEG stored with EXIF orientation 6 (rotate 90° clockwise to
/// show): 20 x 40 as shown. False when it cannot be written.
inline bool write_rotated_jpeg(std::filesystem::path const& path) {
    return write_bytes(path, jpeg_with_orientation(6));
}

/// A 40 x 20 JPEG without EXIF. False when it cannot be written.
inline bool write_plain_jpeg(std::filesystem::path const& path) { return write_bytes(path, plain_jpeg_bytes()); }

/// An EXIF tag of exif_tiff: type 3 (SHORT, `numerator`), 4 (LONG) or 5 (RATIONAL).
struct ExifTag {
    std::uint16_t tag;
    std::uint16_t type;
    std::uint32_t numerator;
    std::uint32_t denominator = 1;
};

/// TIFF bytes ("II" or "MM"): IFD0 with only the Exif IFD pointer, the Exif IFD with `tags`.
inline std::string exif_tiff(std::vector<ExifTag> const& tags, bool big_endian = false) {
    std::string out;
    auto put = [&](std::uint32_t v, int n) {
        for (int i = 0; i < n; ++i) {
            int const shift = 8 * (big_endian ? n - 1 - i : i);
            out.push_back(static_cast<char>((v >> shift) & 0xFF));
        }
    };
    out.append(big_endian ? "MM" : "II", 2);
    put(42, 2);
    put(8, 4);
    put(1, 2);  // IFD0: the Exif IFD pointer
    put(0x8769, 2);
    put(4, 2);
    put(1, 4);
    put(26, 4);
    put(0, 4);
    put(static_cast<std::uint32_t>(tags.size()), 2);  // Exif IFD at 26
    std::uint32_t data_off = 26 + 2 + 12 * static_cast<std::uint32_t>(tags.size()) + 4;
    for (auto const& t : tags) {
        put(t.tag, 2);
        put(t.type, 2);
        put(1, 4);
        if (t.type == 5) {
            put(data_off, 4);
            data_off += 8;
        } else {
            put(t.numerator, t.type == 3 ? 2 : 4);
            if (t.type == 3) put(0, 2);
        }
    }
    put(0, 4);
    for (auto const& t : tags) {
        if (t.type != 5) continue;
        put(t.numerator, 4);
        put(t.denominator, 4);
    }
    return out;
}

/// `jpeg` (SOI ..) with an APP1 "Exif\0\0" + exif_tiff(tags) right after SOI.
inline std::string jpeg_with_exif(std::string jpeg, std::vector<ExifTag> const& tags, bool big_endian = false) {
    std::string const tiff = std::string("Exif\0\0", 6) + exif_tiff(tags, big_endian);
    std::string app1("\xFF\xE1", 2);
    app1.push_back(static_cast<char>((tiff.size() + 2) >> 8));
    app1.push_back(static_cast<char>((tiff.size() + 2) & 0xFF));
    jpeg.insert(2, app1 + tiff);
    return jpeg;
}

